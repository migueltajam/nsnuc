ACCENTS = {'´': ['..##', '.##.'], '¨': ['##.##'], '~': ['.#.##', '##.#.']}
def accented(base, acc, name):
    rows, top = G[base]
    w = len(rows[0])
    a = ACCENTS[acc]
    aw = len(a[0])
    pad = (w - aw) // 2
    arows = ['.' * pad + r + '.' * (w - aw - pad) for r in a]
    G[name] = (arows + ['.' * w] * (1 if acc != '~' else 1) + rows, top + len(arows) + 1)
for b, ch in zip('AEIOU', 'ÁÉÍÓÚ'): accented(b, '´', ch)
accented('U', '¨', 'Ü'); accented('N', '~', 'Ñ')

def build(path_base):
    order = ['.notdef', 'space'] + [f'u{ord(c):04X}' for c in G]
    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: 'space', 160: 'space'}
    for c in G: cmap[ord(c)] = f'u{ord(c):04X}'
    # Minúsculas = mayúsculas
    for c in list(G):
        lo = c.lower()
        if lo != c and len(lo) == 1 and ord(lo) not in cmap: cmap[ord(lo)] = f'u{ord(c):04X}'
    fb.setupCharacterMap(cmap)
    glyphs, metrics = {}, {}
    empty = TTGlyphPen(None); glyphs['.notdef'] = empty.glyph(); metrics['.notdef'] = (700, 0)
    sp = TTGlyphPen(None); glyphs['space'] = sp.glyph(); metrics['space'] = (500, 0)
    for c, (rows, top) in G.items():
        pen = TTGlyphPen(None)
        for r, row in enumerate(rows):
            y1 = (top - r) * PX; y0 = y1 - PX
            x = 0
            while x < len(row):
                if row[x] == '#':
                    x2 = x
                    while x2 < len(row) and row[x2] == '#': x2 += 1
                    pen.moveTo((x * PX, y0)); pen.lineTo((x * PX, y1)); pen.lineTo((x2 * PX, y1)); pen.lineTo((x2 * PX, y0)); pen.closePath()
                    x = x2
                else:
                    x += 1
        name = f'u{ord(c):04X}'
        glyphs[name] = pen.glyph()
        metrics[name] = ((len(rows[0]) + 1) * PX, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASC, descent=-DESC)
    fb.setupNameTable({'familyName': 'NSNUC Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=ASC, sTypoDescender=-DESC, usWinAscent=ASC, usWinDescent=DESC, sCapHeight=CAP * PX, sxHeight=CAP * PX)
    fb.setupPost()
    fb.save(path_base + '.ttf')
    fb.font.flavor = 'woff'
    fb.font.save(path_base + '.woff')

if __name__ == '__main__':
    out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'fonts', 'nsnuc-pixel')
    build(out)
